import { startCapture, finishCapture } from './capture-generation'
import { AiClientError, SEO_CONTEXT_MAX_CHARS } from '@ech/ai-contracts'
import type { AgentActor } from '@/lib/ai-platform/context'
import type { AiSkipReason } from './generation-actor'

export type SEOMetaOutput = {
    title: string
    description: string
}

const META_TIMEOUT_MS = 15000 // fail fast for the queue

function templateMeta(type: 'page' | 'product', itemName: string, siteName: string): SEOMetaOutput {
    return type === 'product'
        ? {
            title: `${itemName} | ${siteName} | Buy Online Malaysia`,
            description: `Shop ${itemName} at ${siteName}. High quality and best prices in Malaysia. Buy online today!`,
        }
        : {
            title: `${itemName} | ${siteName} Online Malaysia`,
            description: `Welcome to ${siteName}'s ${itemName} page. Discover our services and offerings in Malaysia.`,
        }
}

function cappedTemplateMeta(type: 'page' | 'product', itemName: string, siteName: string): SEOMetaOutput {
    const template = templateMeta(type, itemName, siteName)
    return { title: template.title.substring(0, 60), description: template.description.substring(0, 160) }
}

/**
 * @param actor Signed-in caller + workspace. When given (callers pass one only
 *   if `isAiTasksEnabled()`), the meta is generated by the ECH AI platform
 *   task `seo.generate-meta`; without one the template meta is returned.
 */
export async function generateAutoSEOMeta(
    type: 'page' | 'product',
    itemName: string,
    siteName: string,
    context?: string,
    keywords?: string[],
    signal?: AbortSignal,
    actor?: AgentActor | null,
    /** Why `actor` is missing although AI may be configured; written on the record of the template fallback. */
    options: { skipReason?: AiSkipReason; siteId?: string | number | null } = {},
): Promise<SEOMetaOutput> {
    if (signal?.aborted) throw new DOMException('Aborted', 'AbortError')
    const promptSummary = `${type}:${itemName} | site:${siteName}`
    const cap = await startCapture({
        endpoint: 'generate-meta',
        prompt: promptSummary,
        category: type,
        // relationship columns are integers: the actor carries the workspace id as text
        ...(actor ? { userId: actor.user.id, tenantId: /^\d+$/.test(actor.tenantId) ? Number(actor.tenantId) : actor.tenantId } : {}),
        ...(options.siteId != null ? { siteId: options.siteId } : {}),
    })

    if (actor) {
        return generateMetaOnPlatform(actor, cap, { type, itemName, siteName, context, keywords, signal })
    }

    // No signed-in caller (imports, scripts) or no AI platform: template meta.
    const fallback = templateMeta(type, itemName, siteName)
    await finishCapture(cap, {
        status: 'success',
        outputSnapshot: { path: 'no-actor-fallback', ...(options.skipReason ? { aiSkipReason: options.skipReason } : {}), ...fallback },
    })
    return fallback
}

type Capture = Awaited<ReturnType<typeof startCapture>>

async function generateMetaOnPlatform(
    actor: AgentActor,
    cap: Capture,
    args: {
        type: 'page' | 'product'
        itemName: string
        siteName: string
        context?: string
        keywords?: string[]
        signal?: AbortSignal
    },
): Promise<SEOMetaOutput> {
    const { type, itemName, siteName, context, keywords, signal } = args
    // Loaded lazily: this module is reachable from collection hooks (payload
    // config), which must not pull the server-only platform client.
    const { getAiTaskClient } = await import('@/lib/ai-platform/task-client')
    const timeout = AbortSignal.timeout(META_TIMEOUT_MS)
    try {
        const { output } = await getAiTaskClient(actor).runTask(
            'seo.generate-meta',
            {
                type,
                itemName: itemName.slice(0, 300),
                siteName: (siteName || 'Website').slice(0, 200),
                context: context ? context.slice(0, SEO_CONTEXT_MAX_CHARS) : undefined,
                keywords: (keywords ?? []).slice(0, 30),
            },
            { signal: signal ? AbortSignal.any([signal, timeout]) : timeout },
        )
        const result: SEOMetaOutput = {
            title: (output.metaTitle || `${itemName} | ${siteName}`).substring(0, 60),
            description: (output.metaDescription || '').substring(0, 160),
        }
        await finishCapture(cap, { status: 'success', outputSnapshot: { path: 'ai-platform', ...result } })
        return result
    } catch (error: unknown) {
        if (signal?.aborted) {
            await finishCapture(cap, { status: 'failed', error: 'aborted' })
            throw new DOMException('Aborted', 'AbortError')
        }
        // Workspace quota reached: same template fallback as the legacy rate-limit path.
        if (error instanceof AiClientError && error.status === 429) {
            const rateFallback = cappedTemplateMeta(type, itemName, siteName)
            await finishCapture(cap, { status: 'success', outputSnapshot: { path: 'rate-limit-fallback', ...rateFallback } })
            return rateFallback
        }
        const message = error instanceof Error ? error.message : 'Unknown error'
        console.error('[AI] SEO Meta Generation failed:', message)
        await finishCapture(cap, { status: 'failed', error: message })
        throw new Error(`AI meta generation failed: ${message}`)
    }
}
