/** Truncate a string on a word boundary so the tail is never mid-word. */
function truncateOnWord(str: string, maxChars: number): string {
    if (!str) return ''
    if (str.length <= maxChars) return str
    const sliced = str.slice(0, maxChars - 1)
    const lastSpace = sliced.lastIndexOf(' ')
    if (lastSpace > maxChars * 0.6) return sliced.slice(0, lastSpace).trimEnd() + '…'
    return sliced.trimEnd() + '…'
}

/** Cap a string at `maxWords`; keeps words intact. */
function capWords(str: string, maxWords: number): string {
    if (!str) return ''
    const words = str.split(/\s+/).filter(Boolean)
    if (words.length <= maxWords) return words.join(' ')
    return words.slice(0, maxWords).join(' ')
}

function capitalizeFirstLetter(s: string): string {
    if (!s) return s
    return s.charAt(0).toUpperCase() + s.slice(1)
}

/** Resolve mood CTA with defensive fallback to the legacy labels. */
function resolveLibraryCTA(
    mood: ThemeMood | undefined,
    category: string,
    role: 'primary' | 'secondary',
    language?: string,
    localeStrings?: LocaleStructuralStrings | null,
): string {
    const localized = resolveLocaleStructuralStrings(language) ?? localeStrings
    if (localized && language?.split('-')[0] !== 'en') {
        return role === 'primary'
            ? localized.navigation.getStarted
            : localized.navigation.about
    }
    if (mood) return getCategoryCTA(mood, category, role)
    return role === 'primary' ? 'Get Started' : 'Learn More'
}

/**
 * Weave user biz into a hero block. Builds headline from user name + first
 * product / first words of description, subheadline from user description.
 * When userBiz is empty, returns null so caller keeps the canned hero.
 */
function threadHeroBiz(
    userBiz: Partial<BusinessSample> | undefined,
    mood: ThemeMood | undefined,
    category: string,
    language?: string,
    localeStrings?: LocaleStructuralStrings | null,
): { headline: string; subheadline: string; ctaPrimary: string; ctaSecondary: string } | null {
    if (!userBiz) return null
    const name = (userBiz.name ?? '').trim()
    const description = (userBiz.description ?? '').trim()
    const topProduct = userBiz.products?.[0]?.trim() || undefined
    if (!name && !description && !topProduct) return null

    // Headline: "{name} — {tail}" where tail is a topProduct or the first 5 words of description.
    const descWords = description.split(/\s+/).filter(Boolean)
    const tail = topProduct
        ? capitalizeFirstLetter(topProduct)
        : descWords.length >= 3
            ? descWords.slice(0, 5).join(' ')
            : ''
    const anchor = name || topProduct || description
    const headlineRaw = tail ? `${anchor} — ${tail}` : anchor
    // Consistency rule C3 — cap hero headline at 10 words.
    const headline = capWords(headlineRaw, 10)

    // Subheadline: first 140 chars of description on word boundary.
    const subheadline = description
        ? truncateOnWord(description, 140)
        : topProduct || name

    return {
        headline,
        subheadline,
        ctaPrimary: resolveLibraryCTA(mood, category, 'primary', language, localeStrings),
        ctaSecondary: resolveLibraryCTA(mood, category, 'secondary', language, localeStrings),
    }
}

type Block = Record<string, unknown>

function substituteBusinessName(str: string, name?: string): string {
    if (!name) return str
    return str.replace(/\$\{businessName\}/g, name).replace(/\{businessName\}/g, name)
}

/**
 * Plan 2253 Phase 03 amendment v3 — originally used modulo which had the same
 * djb2 clustering bug as R3. Now delegates to shared `seededShufflePick`
 * (Fisher-Yates) so same-category businesses land on different BusinessSamples.
 */
function pickSeeded<T>(arr: readonly T[], seed: number): T | undefined {
    return seededShufflePick(arr, seed)
}

/**
 * Shuffle a pool of items by seed so different businesses in the same category
 * pull different subsets / orderings.
 *
 * Plan 2253 Phase 03 — fixes R5 (padItems reuse). Originally used modulo
 * rotation which re-introduced the R3 clustering bug (common business names
 * collide on `seed % pool.length`). Now uses Fisher-Yates seeded shuffle via
 * `seededShuffle` — same helper Phase 02 uses for theme preset distribution.
 *
 * Plan 2253 Phase 03 amendment (2026-04-15) after variety-delta measurement
 * showed testimonial collision regressed on 4/5 categories due to the modulo
 * variant of this helper.
 */
function rotateSlice<T>(pool: readonly T[], seed: number): T[] {
    if (pool.length === 0) return []
    return seededShuffle(pool, seed)
}

/**
 * Build a fully-formed block from the content library.
 * Returns null if no suitable content exists for (blockType, category).
 */
export function buildBlockFromLibrary(
    blockType: string,
    category: string,
    ctx: InjectionContext = {},
): Block | null {
    // Content-heavy blocks (testimonials, features, faq) use English-only library
    // data. For non-English sites, returning null tells the structure-enforcer to
    // skip injection — GPT should provide these blocks in the target language.
    // Structural blocks (nav, footer, hero, contact, about, cta) are still injected.
    const language = ctx.language?.split('-')[0]
    const isNonEnglish = Boolean(language && language !== 'en')
    const hasLocalizedServiceLibrary = blockType === 'service-cards' && language === 'ms'
    if (
        isNonEnglish
        && CONTENT_BLOCKS_NO_ENGLISH_PAD.has(blockType)
        && !hasLocalizedServiceLibrary
    ) {
        return null
    }

    // Fallback to 'business' category content when category is unknown — ensures
    // gap-filler can still inject generic blocks for long-tail industries.
    const content = getCategoryContent(category) ?? getCategoryContent('business')
    if (!content) return null

    // Plan 2253 Phase 03 — fixes R4 (businesses[0] hardcode).
    // Rotate the BusinessSample pick by seed so different businesses in the same
    // category inject different canned copy + tagline + description when the AI
    // underfills and structure-enforcer has to gap-fill.
    const bizSeed = ctx.seed ?? 0
    const librarySample: BusinessSample | undefined =
        pickSeeded(content.businesses, bizSeed) ?? content.businesses[0]
    // Plan 07 — user-supplied fields override canned samples.
    const userBiz = ctx.userBiz
    // #2103 A1: with a real merchant (userBiz) the library sample's identity and
    // contact must never be read, so every `biz?.x` below sees them empty.
    // Gallery/preview callers (no userBiz) keep the sample.
    const biz: BusinessSample | undefined = librarySample && userBiz
        ? withoutLibraryIdentity(librarySample, userBiz)
        : librarySample
    const name = userBiz?.name
        ?? ctx.businessName
        ?? (isNonEnglish ? undefined : biz?.name)
        ?? ''
    const userDescription = userBiz?.description?.trim() || undefined
    const userTagline = userBiz?.tagline?.trim() || undefined
    const userProducts = (userBiz?.products ?? []).filter((p) => p && p.trim().length > 0)
    const userPhone = userBiz?.phone?.trim() || undefined
    const userEmail = userBiz?.email?.trim() || undefined
    const userAddress = userBiz?.address?.trim() || undefined

    // Seed-rotated content pool slices for testimonials / faqs / features so
    // within-category businesses pull different subsets of the library.
    const testimonialSlice = rotateSlice(content.testimonials, bizSeed)
    const faqSlice = rotateSlice(content.faqItems, bizSeed ^ hashString('faq'))

    // Plan 2253 follow-up (260415-0900) — merged business sample for
    // delegation to template-composer builders. Library default (biz) +
    // user overrides from ctx.userBiz (name, tagline, products, contact).
    // Used by features/stats/pricing/team/service-cards delegation below.
    const mergedBiz: BusinessSample = {
        ...(biz ?? ({} as BusinessSample)),
        ...(userBiz ?? {}),
    }

    const i18n = getBlockStrings(ctx.language)
    const localized = isNonEnglish
        ? resolveLocaleStructuralStrings(ctx.language) ?? ctx.localeStrings ?? null
        : null
    const navigation = localized?.navigation ?? i18n.navigation

    switch (blockType) {
        case 'navigation':
            return {
                blockType: 'navigation',
                variant: 'pill',
                logoText: name,
                links: [
                    { label: localized?.navigation.home ?? name, url: '/' },
                    { label: localized?.navigation.about ?? name, url: '/about' },
                    { label: localized?.navigation.services ?? userProducts[0] ?? name, url: '/services' },
                    { label: localized?.navigation.contact ?? name, url: '/contact' },
                ],
                ctaButton: {
                    show: true,
                    label: localized?.navigation.getStarted ?? userProducts[0] ?? name,
                    url: '/contact',
                },
            }

        case 'hero': {
            // Plan 260415 Phase 03 — delegate to composer buildHero when the
            // merged biz sample has a name + description/tagline/products. It
            // derives `name — top product` headlines + truncated descriptions
            // instead of canned "Welcome to ${name}" strings. Falls back to
            // the legacy user-thread path on any error.
            const canDelegate = !isNonEnglish
                && !!(mergedBiz.name && (mergedBiz.description || mergedBiz.tagline || (mergedBiz.products && mergedBiz.products.length > 0)))
            if (canDelegate) {
                try {
                    const composed = composerBuildHero(mergedBiz, category, bizSeed, ctx.mood, ctx.language) as Block
                    // Ensure CTA buttons align with mood (composer emits generic labels).
                    const primaryLabel = resolveLibraryCTA(ctx.mood, category, 'primary', ctx.language, localized)
                    const secondaryLabel = resolveLibraryCTA(ctx.mood, category, 'secondary', ctx.language, localized)
                    return {
                        ...composed,
                        ctaButtons: [
                            { label: primaryLabel, url: '/contact', style: 'primary' },
                            { label: secondaryLabel, url: '/about', style: 'secondary' },
                        ],
                    }
                } catch (err) {
                    console.warn('[content-injection] composerBuildHero failed, falling back:', err)
                }
            }

            // Legacy fallback — Plan 07 user-thread path kept as defensive branch.
            const userHero = threadHeroBiz(userBiz, ctx.mood, category, ctx.language, localized)
            const headline = userHero?.headline
                ?? (isNonEnglish
                    ? userProducts[0] ?? name
                    : substituteBusinessName(biz?.heroHeadline ?? `Welcome to ${name}`, name))
            const subheadline = userHero?.subheadline
                ?? (isNonEnglish
                    ? userDescription ?? userTagline ?? userProducts[0] ?? name
                    : substituteBusinessName(
                    biz?.heroSubheadline ?? biz?.description ?? 'Quality service for every customer.',
                    name,
                ))
            const primaryLabel = userHero?.ctaPrimary
                ?? resolveLibraryCTA(ctx.mood, category, 'primary', ctx.language, localized)
            const secondaryLabel = userHero?.ctaSecondary
                ?? resolveLibraryCTA(ctx.mood, category, 'secondary', ctx.language, localized)
            return {
                blockType: 'hero',
                variant: 'gradient',
                headline,
                subheadline,
                ctaButtons: [
                    { label: primaryLabel, url: '/contact', style: 'primary' },
                    { label: secondaryLabel, url: '/about', style: 'secondary' },
                ],
            }
        }

        case 'about':
            return {
                blockType: 'about',
                variant: 'simple',
                sectionLabel: localized?.sections.about ?? i18n.footer.aboutUs,
                headline: localized
                    ? `${localized.sections.aboutHeadlinePrefix} ${name}`.trim()
                    : `${i18n.about.headlinePrefix} ${name}`,
                // Plan 07 — prefer user description, fall back to canned pool.
                // #2103 A1: with real user data never fall back to the library sample's
                // description (it describes a different, fictional business).
                body: userDescription
                    ?? (userBiz ? name : (isNonEnglish ? undefined : biz?.description))
                    ?? (isNonEnglish ? name : undefined)
                    ?? `${name} is dedicated to delivering exceptional experiences to every customer.`,
            }

        case 'testimonials': {
            // #2103 A1: real quotes from FACTS, else one invitation card — never library people.
            const block = composerBuildTestimonials(mergedBiz, ctx.language)
            return { ...block, headline: i18n.testimonials.headline } as Block
        }

        case 'faq': {
            // #2103 A1: only questions answerable from FACTS. Nothing to say → don't inject an empty FAQ.
            const block = composerBuildFAQ(mergedBiz, ctx.language) as Block
            const items = (block.items as unknown[]) ?? []
            if (items.length === 0) return null
            return { blockType: 'faq', variant: 'accordion', headline: i18n.faq.headline, faqs: items } as Block
        }

        case 'cta':
            return {
                blockType: 'cta',
                variant: 'banner',
                headline: localized?.sections.contact ?? i18n.cta.headlineReady(name),
                // Plan 07 — user tagline > canned tagline > generic.
                subheadline:
                    userTagline
                    ?? (userDescription ? truncateOnWord(userDescription, 140) : undefined)
                    ?? (isNonEnglish ? name : biz?.tagline)
                    ?? i18n.cta.subheadline,
                ctaButton: {
                    label: resolveLibraryCTA(ctx.mood, category, 'primary', ctx.language, localized),
                    url: '/contact',
                    style: 'primary',
                },
            }

        case 'contact':
            return {
                blockType: 'contact',
                variant: 'form',
                headline: localized?.contact.headline ?? i18n.contact.headline,
                subheadline: localized?.contact.subheadline
                    ?? (isNonEnglish ? userDescription ?? name : i18n.contact.subheadline),
                sectionLabel: localized?.sections.contact ?? navigation.contact,
                // Plan 07 — user-supplied contact fields win over canned pool.
                // Real generation (userBiz present) never falls back to canned sample
                // contact data; gallery/preview callers (no userBiz) keep the sample.
                address: userAddress ?? (userBiz ? '' : biz?.address ?? ''),
                phone: userPhone ?? (userBiz ? '' : biz?.phone ?? ''),
                // null not '' — Payload email-type field validates format even without required:true,
                // so empty string causes ValidationError on publish.
                email: userEmail ?? (userBiz ? null : biz?.email ?? null),
                submitLabel: localized?.contact.submitLabel ?? i18n.contact.submitLabel,
                phoneLabel: localized?.contact.phoneLabel ?? i18n.contact.phoneLabel,
                addressLabel: localized?.contact.addressLabel ?? i18n.contact.addressLabel,
                emailLabel: localized?.contact.emailLabel ?? i18n.contact.emailLabel,
                formFields: [
                    { fieldName: 'name', label: localized?.contact.nameLabel ?? i18n.contact.nameLabel, fieldType: 'text', required: true },
                    { fieldName: 'email', label: localized?.contact.emailLabel ?? i18n.contact.emailLabel, fieldType: 'email', required: true },
                    { fieldName: 'message', label: localized?.contact.messageLabel ?? i18n.contact.messageLabel, fieldType: 'textarea', required: true },
                ],
            }

        case 'footer':
            return {
                blockType: 'footer',
                variant: 'simple',
                logoText: name,
                // Plan 07 — user tagline/description wins over canned.
                tagline: userTagline ?? (userDescription ? truncateOnWord(userDescription, 90) : biz?.tagline ?? ''),
                copyrightText: localized
                    ? `© ${new Date().getFullYear()} ${name}. ${localized.footer.allRightsReserved}`
                    : `© ${new Date().getFullYear()} ${name}. ${i18n.footer.allRightsReserved}`,
                columns: [
                    { title: localized?.footer.exploreLabel ?? i18n.footer.explore, links: [{ label: navigation.home, url: '/' }, { label: navigation.about, url: '/about' }] },
                    { title: navigation.contact, links: [{ label: navigation.contact, url: '/contact' }] },
                ],
            }

        case 'features':
            // #2103 A1: product/description based only (see template-composer buildFeatures).
            return composerBuildFeatures(mergedBiz, category, ctx.language)

        case 'stats': {
            // #2103 A1: real numbers only; fewer than two → nothing to inject.
            const block = composerBuildStats(mergedBiz, ctx.language)
            return (block.stats as unknown[]).length > 0 ? block : null
        }

        case 'team':
            // #2103 A1: owner/brand only — no invented names or credentials.
            return composerBuildTeam(mergedBiz, ctx.language)

        case 'service-cards': {
            // Plan 2253 follow-up (260415-0900) — delegate to template-composer
            // buildServiceCards for category-curated services ("Halal Catering"
            // for fnb; "Dental Implants" for health; etc). Composer also reads
            // biz.products so user-supplied services drive output when provided.
            try {
                return composerBuildServiceCards(mergedBiz, category, ctx.language)
            } catch (err) {
                console.warn('[content-injection] composerBuildServiceCards failed, falling back:', err)
            }

            const pool = [
                { icon: '⭐', title: 'Premium Service', description: 'Our flagship offering.' },
                { icon: '🚀', title: 'Fast Delivery', description: 'Quick turnaround on every job.' },
                { icon: '💎', title: 'Custom Solutions', description: 'Tailored to your needs.' },
                { icon: '🛡️', title: 'Ongoing Support', description: 'We stand behind our work.' },
                { icon: '🎨', title: 'Expert Consultation', description: 'Guidance from seasoned professionals.' },
                { icon: '🔧', title: 'Flexible Options', description: 'Packages that fit every need.' },
                { icon: '✅', title: 'Guaranteed Results', description: 'Quality you can measure.' },
                { icon: '📞', title: 'Dedicated Account Manager', description: 'One point of contact, always.' },
            ]
            const shuffled = seededShuffle(pool, bizSeed ^ hashString('service-cards'))
            return {
                blockType: 'service-cards',
                variant: 'grid',
                headline: i18n.serviceCards.headline,
                services: shuffled.slice(0, 4),
            }
        }

        case 'products-featured':
            // #2103 A3: the shop's own products, shown on the home page (rendered from the catalogue).
            return {
                blockType: 'products-featured',
                variant: 'hero-product',
                headline: isNonEnglish ? name : (language === 'ms' ? 'Produk Pilihan' : 'Featured Products'),
            }

        case 'gallery': {
            return {
                blockType: 'gallery',
                variant: 'grid',
                sectionLabel: localized?.sections.gallery,
                headline: localized?.sections.gallery
                    ?? (isNonEnglish ? name : i18n.gallery.headline),
                // Empty images array — media-injector fills from Unsplash
                images: Array.from({ length: 6 }, () => ({})),
            }
        }

        case 'newsletter': {
            return {
                blockType: 'newsletter',
                variant: 'banner',
                sectionLabel: localized?.sections.newsletter,
                headline: localized?.sections.newsletter
                    ?? (isNonEnglish ? name : i18n.newsletter.headlineStayUpdated(name)),
                subheadline:
                    userTagline
                    ?? (userDescription ? truncateOnWord(userDescription, 140) : undefined)
                    ?? (isNonEnglish ? name : i18n.newsletter.subheadlineFallback),
                buttonLabel: localized?.newsletter.buttonLabel
                    ?? (isNonEnglish ? name : i18n.newsletter.subscribeLabel),
                placeholder: localized?.newsletter.emailPlaceholder
                    ?? userEmail
                    ?? (isNonEnglish ? name : 'your@email.com'),
            }
        }

        case 'pricing': {
            // #2103 A1: plans are the merchant's own priced products — never invented tiers.
            const block = composerBuildPricing(mergedBiz, ctx.language)
            return (block.plans as unknown[]).length > 0 ? block : null
        }

        case 'logo-cloud':
        case 'client-logos': // backward compat alias for saved pages
            // #2103 A1: payment methods the tenant enabled; never third-party brands.
        {
            const block = composerBuildClientLogos(mergedBiz, ctx.language)
            if ((block.logos as unknown[]).length === 0) return null
            return { ...block, headline: localized?.sections.clientLogos ?? (isNonEnglish ? name : groundedLogoHeadline(ctx.language)) } as Block
        }

        default: {
            // Try industry blocks for category-specific signatures
            const sig = content.industryBlocks.find((b) => b.blockType === blockType)
            if (sig) return { ...sig } as Block
            return null
        }
    }
}

/**
 * Pad an existing item array up to `minCount` by pulling from content library.
 * Returns the padded array. Handles testimonials, faq, team, features duplication.
 *
 * Plan 2253 Phase 03 — fixes R5 (padItems pool reuse). Accepts ctx so the pool
 * start offset rotates per-business; same-category gens no longer converge on
 * the same first 4 testimonials.
 */
/**
 * Block types where item copy (quotes, Q&A, feature titles) must come from GPT
 * for non-English sites. Library content is English-only — padding these blocks
 * with library items corrupts language consistency.
 */
const NEVER_PAD_BLOCKS: ReadonlySet<string> = new Set([
    'testimonials',
    'faq',
    'team',
    'stats',
    'pricing',
    'logo-cloud',
    'client-logos',
])

const CONTENT_BLOCKS_NO_ENGLISH_PAD = new Set([
    'testimonials',
    'faq',
    'features',
    'team',
    'stats',
    'service-cards',
    'pricing',
])

function normalizeServiceTitle(value: unknown): string {
    return typeof value === 'string'
        ? value.trim().replace(/\s+/g, ' ').toLocaleLowerCase()
        : ''
}

function isSameServiceTitle(left: string, right: string): boolean {
    if (left === right) return true
    const shorterLength = Math.min(left.length, right.length)
    return shorterLength >= 4 && (left.includes(right) || right.includes(left))
}

/**
 * Fill localized service cards from the user's comma-separated products.
 * Product names and business copy are already in the requested language, so
 * this path can repair thin AI output without leaking English library content.
 */
function padLocalizedServiceCards(
    existing: readonly unknown[],
    minCount: number,
    ctx: InjectionContext,
): unknown[] {
    const result = [...existing]
    const products = (ctx.userBiz?.products ?? [])
        .map((product) => product.trim())
        .filter(Boolean)
    if (products.length === 0) return result

    const existingTitles = result
        .filter((item): item is Block => typeof item === 'object' && item !== null)
        .map((item) => normalizeServiceTitle(item.title))
        .filter(Boolean)
    const existingIcons = result
        .filter((item): item is Block => typeof item === 'object' && item !== null)
        .map((item) => typeof item.icon === 'string' ? item.icon : '')
        .filter(Boolean)
    const description = ctx.userBiz?.description?.trim()
        || ctx.userBiz?.tagline?.trim()

    for (const product of products) {
        if (result.length >= minCount) break
        const productTitle = normalizeServiceTitle(product)
        if (
            !productTitle
            || existingTitles.some((title) => isSameServiceTitle(title, productTitle))
        ) {
            continue
        }

        const icon = existingIcons.length > 0
            ? existingIcons[result.length % existingIcons.length]
            : 'Star'
        result.push({
            title: product,
            description: description || product,
            icon,
        })
        existingTitles.push(productTitle)
    }

    return result
}

export function padItems(
    blockType: string,
    existing: readonly unknown[],
    minCount: number,
    category: string,
    ctx: InjectionContext = {},
): unknown[] {
    if (existing.length >= minCount) return [...existing]
    // #2103 A1: these blocks only ever carry real facts — never pad them with invented items.
    if (NEVER_PAD_BLOCKS.has(blockType)) return [...existing]

    // For non-English sites, skip library padding for content-heavy blocks.
    // GPT has already generated items in the target language; adding English
    // library items would produce mixed-language output (e.g. 3 Vietnamese
    // FAQ + 2 English FAQ). Return GPT's items as-is even if below minCount.
    const language = ctx.language?.split('-')[0]
    const hasLocalizedServiceLibrary = blockType === 'service-cards' && language === 'ms'
    if (
        blockType === 'service-cards'
        && language
        && language !== 'en'
        && !hasLocalizedServiceLibrary
    ) {
        return padLocalizedServiceCards(existing, minCount, ctx)
    }
    if (
        language
        && language !== 'en'
        && CONTENT_BLOCKS_NO_ENGLISH_PAD.has(blockType)
        && !hasLocalizedServiceLibrary
    ) {
        return [...existing]
    }

    const content = getCategoryContent(category)
    const result: unknown[] = [...existing]
    const baseSeed = ctx.seed ?? 0

    if (blockType === 'testimonials' || blockType === 'faq') {
        // #2103 A1: real items are never padded with library people/Q&A — fewer is honest.
        return result
    } else {
        // Generic padding — inject from library block, dedup by `title` field
        // (features, service-cards have title). Avoids "Quality Service" appearing twice.
        // User products are already in `existing`. Build the padding pool from
        // curated category services so it can contribute a distinct fourth
        // card instead of returning the same user-derived cards again.
        const libraryCtx = blockType === 'service-cards' && ctx.userBiz
            ? { ...ctx, userBiz: { ...ctx.userBiz, products: undefined } }
            : ctx
        const libBlock = buildBlockFromLibrary(blockType, category, libraryCtx)
        if (libBlock) {
            const field = ITEM_FIELD_BY_BLOCK[blockType]
            if (field && Array.isArray(libBlock[field])) {
                const libItems = libBlock[field] as unknown[]
                const existingTitles = new Set(
                    result
                        .filter((r): r is Block => typeof r === 'object' && r !== null)
                        .map((r) => String((r as Block).title ?? (r as Block).name ?? '').toLowerCase())
                        .filter(Boolean),
                )
                for (const item of libItems) {
                    if (result.length >= minCount) break
                    const itemTitle = String(
                        (item as Block).title ?? (item as Block).name ?? '',
                    ).toLowerCase()
                    if (itemTitle && existingTitles.has(itemTitle)) continue
                    result.push(item)
                    if (itemTitle) existingTitles.add(itemTitle)
                }
            }
        }
    }

    return result.slice(0, Math.max(minCount, existing.length))
}
