import { getPayload } from 'payload'
import configPromise from '@payload-config'
import { revalidatePath } from 'next/cache'
import { after } from 'next/server'
import type { AgentActor } from '@/lib/ai-platform/context'
import { generateAutoSEOMeta } from './generate-meta'
import { captureScopeActor, resolveSeoActor, runAsAiActor } from './seo-actor'

type SeoFields = { title?: string | null; description?: string | null }

/** Fields the merchant left empty: only these may be filled by auto-generation (#2083). */
function emptySeoFields(seo: SeoFields | null | undefined): Array<keyof SeoFields> {
    return (['title', 'description'] as const).filter((field) => !seo?.[field]?.trim())
}

async function readSeo(payload: Awaited<ReturnType<typeof getPayload>>, collection: 'pages' | 'products', docId: string | number) {
    const doc = await payload.findByID({ collection, id: docId, depth: 0 })
    return (doc as { seo?: SeoFields | null }).seo
}

/**
 * @param publisher The user whose write triggered this (`req.user` in the hook). Server-side writes
 *   (site generation, status toggles with `overrideAccess`) carry none, so the AI actor active when this is
 *   called is captured too, and `resolveSeoActor` falls back on the site's own generation record. The meta is
 *   generated by the AI platform as that actor, in the site's workspace; with nobody to run as it is template
 *   meta, recorded with the reason.
 */
export async function queueSEOAutoGeneration(
    collection: 'pages' | 'products',
    docId: string | number,
    siteId: string | number,
    name: string,
    context?: string,
    publisher?: unknown,
) {
    // Read before the work leaves the request: the AsyncLocalStorage scope does not follow it into after().
    const scoped = await captureScopeActor()
    const task = () => backgroundSeoProcessor(collection, docId, siteId, name, context, publisher, scoped).catch((err) => {
        console.error('[SEO Queue] Unhandled background error:', err)
    })
    // Inside a request the work runs after the response (serverless keeps it alive);
    // outside one (seed scripts) `after` throws, so it runs detached as before.
    try {
        after(task)
    } catch {
        void task()
    }
}

async function backgroundSeoProcessor(
    collection: 'pages' | 'products',
    docId: string | number,
    siteId: string | number,
    name: string,
    context?: string,
    publisher?: unknown,
    scoped?: AgentActor | null,
) {
    const payload = await getPayload({ config: configPromise })

    let jobId: string | number | null = null

    try {
        // Merchant already wrote both fields: nothing to fill, no job.
        if (emptySeoFields(await readSeo(payload, collection, docId)).length === 0) return

        // 1. Fetch site name
        const site = await payload.findByID({
            collection: 'sites',
            id: siteId,
        })
        const siteName = site.businessName || site.name || 'Website'
        const { actor, skipReason } = await resolveSeoActor(payload, site, { scoped, publisher })

        // Fetch tracked keywords (AC-15)
        const trackedKeywords = ((site as any)?.seo?.trackedKeywords as Array<{ keyword: string }> | undefined)
            ?.map(k => k.keyword).filter(Boolean) || []

        // 2. Create pending job
        const job = await payload.create({
            collection: 'seo-meta-jobs',
            data: {
                targetCollection: collection,
                targetId: String(docId),
                site: siteId,
                status: 'pending',
                retryCount: 0,
            },
        })
        jobId = job.id

        // 3. Generate Meta
        const { title, description } = await runAsAiActor(actor, () => generateAutoSEOMeta(
            collection === 'products' ? 'product' : 'page',
            name,
            siteName,
            context,
            trackedKeywords,
            undefined,
            actor,
            { skipReason, siteId },
        ))

        // 4. Fill only the fields still empty. Re-read first: the merchant may have
        // saved SEO while the meta was being generated.
        const generated: SeoFields = { title, description }
        const current = await readSeo(payload, collection, docId)
        const fills: SeoFields = {}
        for (const field of emptySeoFields(current)) {
            fills[field] = generated[field]
        }
        if (Object.keys(fills).length > 0) {
            // Write the whole group back so merchant values (and ogImage/noIndex) are kept as read.
            await payload.update({ collection, id: docId, data: { seo: { ...current, ...fills } } })
        }

        // 5. Mark Job as Completed
        await payload.update({
            collection: 'seo-meta-jobs',
            id: jobId,
            data: {
                status: 'completed',
            },
        })

        // 6. Revalidate sitemap
        revalidatePath('/sitemap.xml')
        revalidatePath(`/(frontend)/sites/[slug]/sitemap.xml`, 'page')
    } catch (error: any) {
        // Log error to Job Collection
        if (jobId) {
            await payload.update({
                collection: 'seo-meta-jobs',
                id: jobId,
                data: {
                    status: 'failed',
                    errorLog: error.message || 'Unknown error occurred',
                },
            })
        }
    }
}
