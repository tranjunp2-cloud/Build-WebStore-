#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(
  __dirname,
  "../docs/design/Adapt template/static-prototypes/c101",
);
const files = [
  "index.html",
  "products/index.html",
  "articles/index.html",
  "about-us/index.html",
  "contact/index.html",
];
const failures = [];

for (const file of files) {
  const html = fs.readFileSync(path.join(root, file), "utf8");
  const navigationHtml = html.slice(
    html.indexOf('data-block-type="navigation"'),
    html.indexOf("<main"),
  );
  const footerHtml = html.slice(html.indexOf('data-block-type="footer"'));
  if (!html.includes("GENERATED by scripts/export-static-prototypes.cjs"))
    failures.push(`${file}: missing generated-artifact header`);
  if (!html.includes('data-render-provenance="SiteRenderer"'))
    failures.push(`${file}: missing SiteRenderer provenance`);
  if (!html.includes("data-block-type="))
    failures.push(`${file}: missing renderer block annotations`);
  if (!html.includes('data-mapping-status="renderer-generated"'))
    failures.push(`${file}: missing renderer mapping status`);
  if (html.includes("_v2.css") || html.includes("_v2.js"))
    failures.push(`${file}: references handwritten C101 assets`);
  if (
    !html.includes(
      '[style*="opacity: 0"]{opacity:1!important;transform:none!important}',
    )
  )
    failures.push(`${file}: missing frozen Framer Motion snapshot override`);
  if (/<html[^>]*class="[^"]*\bdark\b/.test(html))
    failures.push(`${file}: exported with dashboard dark class`);
  if (/\/(?:__nextjs_font|_next\/static\/media)\//.test(html))
    failures.push(`${file}: contains Next-only font asset URL`);
  if (/name="(?:sentry-trace|baggage)"/.test(html))
    failures.push(`${file}: contains request-specific tracing metadata`);
  if (html.includes("Web Store — Build Beautiful Websites in Minutes"))
    failures.push(`${file}: contains generic application metadata`);
  if (/href="\/(?:products\/beauty-essential|blog\/beauty-note)/.test(html))
    failures.push(`${file}: contains unexported runtime detail link`);
  if (
    /aria-label="Open menu"(?![^>]*disabled)/.test(html) &&
    (!html.includes('data-static-menu-toggle="true"') ||
      !html.includes('data-static-behavior="navigation-carousel"'))
  )
    failures.push(
      `${file}: contains enabled control without exported hydration`,
    );
  if (!navigationHtml.includes('data-block-variant="centered"'))
    failures.push(`${file}: navigation is not centered variant`);
  for (const label of [
    "Home",
    "Product",
    "Blog",
    "Contact",
    "Tracking Order",
  ]) {
    if (!navigationHtml.includes(`>${label}</a>`))
      failures.push(`${file}: missing ${label} navigation link`);
  }
  const fromDirectory = path.posix.dirname(file);
  const expectedNavigationTargets = {
    Contact: path.posix.relative(fromDirectory, "contact/index.html"),
    "Tracking Order": path.posix.relative(
      fromDirectory,
      "order-tracking/index.html",
    ),
  };
  for (const [label, href] of Object.entries(expectedNavigationTargets)) {
    const escapedHref = href.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const escapedLabel = label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    if (
      !new RegExp(
        `<a[^>]*href="${escapedHref}"[^>]*>${escapedLabel}<\\/a>`,
      ).test(navigationHtml)
    )
      failures.push(`${file}: ${label} navigation href is not ${href}`);
  }
  const mobileMenuHtml = navigationHtml.match(
    /<nav class="static-mobile-nav[^>]*>[\s\S]*?<\/nav>/,
  )?.[0];
  if (!mobileMenuHtml)
    failures.push(`${file}: missing static centered mobile navigation`);
  else if ((mobileMenuHtml.match(/<a\b/g) || []).length !== 5)
    failures.push(`${file}: centered mobile navigation must contain 5 links`);
  else if (
    !mobileMenuHtml.includes('aria-label="Mobile navigation"') ||
    !mobileMenuHtml.includes('aria-hidden="true"') ||
    !mobileMenuHtml.includes(" hidden")
  )
    failures.push(`${file}: centered mobile navigation is not accessibly hidden`);
  for (const label of ["Cart", "Checkout", "Order Tracking"]) {
    if (new RegExp(`>${label}</a>`).test(navigationHtml))
      failures.push(`${file}: contains removed ${label} navigation link`);
  }
  if (!footerHtml.includes('data-block-variant="dark-gradient"'))
    failures.push(`${file}: footer is not dark-gradient variant`);
  if (!footerHtml.includes('style="background:#171329;color:#ffffff"'))
    failures.push(`${file}: footer is missing approved dark surface contrast`);
  for (const copy of [
    "QUALITY PRODUCTS",
    "SUPPORT POLICY",
    "INTRODUCE",
    "FOLLOW US",
    "BUSINESS SUITE 19A-24-3",
    "02866542688",
    "c101@primeweb.asia",
    "Copyright © 2022 by Prime Commerce",
  ]) {
    if (!footerHtml.includes(copy))
      failures.push(`${file}: footer missing approved data: ${copy}`);
  }
  if ((footerHtml.match(/aria-label="Visit /g) || []).length !== 3)
    failures.push(`${file}: footer must contain three social links`);
  for (const socialUrl of [
    "https://www.facebook.com/",
    "https://www.youtube.com/",
    "https://www.instagram.com/",
  ]) {
    if (!footerHtml.includes(`href="${socialUrl}"`))
      failures.push(`${file}: footer missing external social URL ${socialUrl}`);
  }

  if (file === "index.html") {
    const carouselAssets = [
      "eyes",
      "body",
      "face",
      "lips",
      "shiseido",
      "lamer",
    ];
    for (const [index, asset] of carouselAssets.entries()) {
      const expectedLoading = index === 0 ? "eager" : "lazy";
      const imagePattern = new RegExp(
        `<img[^>]*data-image-index="${index}"[^>]*loading="${expectedLoading}"[^>]*src="_renderer-assets/c101-${asset}\\.jpg"`,
      );
      if (!imagePattern.test(html))
        failures.push(
          `${file}: missing ${expectedLoading} C101 carousel image ${asset}`,
        );
    }
    if (
      !html.includes('data-static-carousel="true"') ||
      !html.includes('data-static-carousel-track="true"') ||
      !html.includes('data-static-carousel-control="true"')
    )
      failures.push(`${file}: missing exported carousel behavior markers`);

    const aboutHtml = html.match(
      /data-block-type="about"[\s\S]*?(?=data-block-type="|<\/main>)/,
    )?.[0];
    if (!aboutHtml)
      failures.push(`${file}: missing home about renderer output`);
    else {
      if ((aboutHtml.match(/<p\b/g) || []).length !== 2)
        failures.push(`${file}: home about must contain two balanced paragraphs`);
      for (const copy of [
        "BRANCY makes everyday beauty feel simple, thoughtful, and personal.",
        "From gentle formulas to expressive colour",
      ]) {
        if (!aboutHtml.includes(copy))
          failures.push(`${file}: missing approved About copy: ${copy}`);
      }
      if (aboutHtml.includes("Lorem Ipsum"))
        failures.push(`${file}: home about still contains placeholder copy`);
    }
  }

  if (file === "index.html" || file === "products/index.html") {
    const productNames = [
      "La Mer The Body Crème - Body cream 300ml",
      "Coco Cocoa Creme Body Butter",
      "Revealing Body Lotion 10% AHA",
      "Hydrating Cream Cleanser",
      "Radiance Repair Serum",
      "Daily Moisture Cream",
      "Silk Finish Foundation",
      "Refined Facial Mist",
    ];
    for (const name of productNames) {
      if (!html.includes(`alt="${name}"`))
        failures.push(`${file}: missing demo product ${name}`);
    }
    const productGridHtml = html.match(
      /data-block-type="products-grid"[\s\S]*?(?=data-block-type="|<\/main>)/,
    )?.[0];
    if (!productGridHtml)
      failures.push(`${file}: missing products-grid renderer output`);
    else {
      if ((productGridHtml.match(/<img\b/g) || []).length !== 8)
        failures.push(`${file}: products-grid must contain exactly 8 product images`);
      if ((productGridHtml.match(/loading="lazy"/g) || []).length !== 8)
        failures.push(`${file}: products-grid product images must remain lazy`);
      const productImageSources = Array.from(
        productGridHtml.matchAll(/<img[^>]*src="([^"]+)"/g),
        (match) => match[1],
      );
      if (new Set(productImageSources).size !== 8)
        failures.push(`${file}: products-grid product images must be distinct`);
      if (productGridHtml.includes("Lorem Ipsum"))
        failures.push(`${file}: products-grid still contains placeholder copy`);
      for (const price of [1400, 129, 180, 89, 168, 95, 149, 79]) {
        if (!productGridHtml.includes(`RM ${price.toFixed(2)}`))
          failures.push(`${file}: missing demo product price RM ${price.toFixed(2)}`);
      }
      if (
        (productGridHtml.match(
          /data-static-product-destination="representative-pdp"/g,
        ) || []).length !== 1
      )
        failures.push(`${file}: products-grid must contain one representative PDP link`);
      if (
        (productGridHtml.match(
          /data-static-product-destination="products-list"/g,
        ) || []).length !== 7
      )
        failures.push(`${file}: products-grid must contain seven listing fallbacks`);
    }
  }
}

if (failures.length) {
  console.error(failures.join("\n"));
  process.exit(1);
}

console.log(
  `verified ${files.length}/${files.length} C101 renderer-generated pages`,
);
